const AES_RCON = [0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36];

function _xtime(a) { return ((a << 1) ^ (a & 0x80 ? 0x1B : 0)) & 0xFF; }

function _mul(a, b) { let r = 0; while (b) { if (b & 1) r ^= a; a = _xtime(a); b >>= 1; } return r; }

// 列优先状态矩阵
function _bytesToState(bs) {
  const s = [[],[],[],[]];
  for (let i = 0; i < 16; i++) s[i % 4][Math.floor(i / 4)] = bs[i];
  return s;
}
function _stateToBytes(s) {
  const b = new Array(16);
  for (let i = 0; i < 16; i++) b[i] = s[i % 4][Math.floor(i / 4)];
  return b;
}

function _invSubBytes(s) {
  const inv = new Array(256);
  for (let i = 0; i < 256; i++) inv[AES_SBOX[i]] = i;
  for (let c = 0; c < 4; c++) for (let r = 0; r < 4; r++) s[r][c] = inv[s[r][c]];
}

function _invShiftRows(s) {
  for (let r = 1; r < 4; r++) {
    const row = [s[r][0], s[r][1], s[r][2], s[r][3]];
    for (let c = 0; c < 4; c++) s[r][c] = row[(c - r + 4) % 4];
  }
}

function _invMixColumns(s) {
  for (let c = 0; c < 4; c++) {
    const a = [s[0][c], s[1][c], s[2][c], s[3][c]];
    s[0][c] = _mul(a[0],0x0e) ^ _mul(a[1],0x0b) ^ _mul(a[2],0x0d) ^ _mul(a[3],0x09);
    s[1][c] = _mul(a[0],0x09) ^ _mul(a[1],0x0e) ^ _mul(a[2],0x0b) ^ _mul(a[3],0x0d);
    s[2][c] = _mul(a[0],0x0d) ^ _mul(a[1],0x09) ^ _mul(a[2],0x0e) ^ _mul(a[3],0x0b);
    s[3][c] = _mul(a[0],0x0b) ^ _mul(a[1],0x0d) ^ _mul(a[2],0x09) ^ _mul(a[3],0x0e);
  }
}

function _addRoundKey(s, rk, round) {
  for (let c = 0; c < 4; c++)
    for (let r = 0; r < 4; r++)
      s[r][c] ^= rk[round][c][r];
}

function _expandKey(key) {
  const Nk = 4, Nr = 10;
  const w = new Array(44);
  for (let i = 0; i < 4; i++) w[i] = [key[4*i], key[4*i+1], key[4*i+2], key[4*i+3]];
  for (let i = Nk; i < 44; i++) {
    let temp = [...w[i-1]];
    if (i % Nk === 0) {
      temp = [AES_SBOX[temp[1]] ^ AES_RCON[i/Nk], AES_SBOX[temp[2]], AES_SBOX[temp[3]], AES_SBOX[temp[0]]];
    }
    w[i] = [w[i-Nk][0]^temp[0], w[i-Nk][1]^temp[1], w[i-Nk][2]^temp[2], w[i-Nk][3]^temp[3]];
  }
  const rk = [];
  for (let r = 0; r <= Nr; r++) {
    const round = [];
    for (let c = 0; c < 4; c++) round.push([...w[r*4+c]]);
    rk.push(round);
  }
  return rk;
}

function _decryptBlock(block, rk) {
  const Nr = 10;
  let s = _bytesToState(block);
  _addRoundKey(s, rk, Nr);
  for (let r = Nr-1; r >= 1; r--) {
    _invShiftRows(s);
    _invSubBytes(s);
    _addRoundKey(s, rk, r);
    _invMixColumns(s);
  }
  _invShiftRows(s);
  _invSubBytes(s);
  _addRoundKey(s, rk, 0);
  return _stateToBytes(s);
}

function decryptCBC(ciphertext, key, iv) {
  if (ciphertext.length % 16 !== 0) throw new Error("密文长度不是16的倍数");
  const rk = _expandKey(key);
  let prev = [...iv];
  const out = [];
  for (let i = 0; i < ciphertext.length; i += 16) {
    const block = ciphertext.slice(i, i+16);
    const dec = _decryptBlock(block, rk);
    for (let j = 0; j < 16; j++) out.push(dec[j] ^ prev[j]);
    prev = [...block];
  }
  // PKCS7 去填充
  const pad = out[out.length-1];
  if (pad >= 1 && pad <= 16) {
    let valid = true;
    for (let i = out.length - pad; i < out.length; i++) if (out[i] !== pad) { valid = false; break; }
    if (valid) out.splice(out.length - pad, pad);
  }
  return new Uint8Array(out);
}

